import { readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../', import.meta.url));
const assets = path.join(root, 'src/assets');
const output = path.join(assets, 'optimized');
await mkdir(output, { recursive: true });
const sources = ['hero-fireplace.jpg', ...(await readdir(path.join(assets, 'portfolio'))).filter(name => name.endsWith('.jpg')).sort().map(name => 'portfolio/' + name)];
// Match the centered object-cover crop on portrait phones, avoiding unused sides.
for (const width of [320, 540]) {
  await sharp(path.join(assets, 'hero-fireplace.jpg'))
    .resize({ width, height: width * 2, fit: 'cover', position: 'centre' })
    .webp({ quality: 80, effort: 6 })
    .toFile(path.join(output, 'hero-fireplace-mobile-' + width + '.webp'));
}
const imports = [];
const records = [];
for (const [index, source] of sources.entries()) {
  const input = path.join(assets, source);
  const { width, height } = await sharp(input).metadata();
  const name = path.basename(source, '.jpg');
  const widths = [...new Set([480, 800, Math.min(1280, width), width])].filter(size => size <= width).sort((a, b) => a - b);
  const variants = [];
  for (const size of widths) {
    const filename = name + '-' + size + '.webp';
    await sharp(input).resize({ width: size, withoutEnlargement: true }).webp({ quality: 80, effort: 6 }).toFile(path.join(output, filename));
    const variable = 'image' + index + '_' + size;
    imports.push('import ' + variable + ' from "./optimized/' + filename + '";');
    variants.push({ variable, size });
  }
  const fallback = variants.at(-1);
  records.push('  [' + fallback.variable + ']: { width: ' + fallback.size + ', height: ' + Math.round(height * fallback.size / width) + ', srcSet: [' + variants.map(v => v.variable + ' + " ' + v.size + 'w"').join(', ') + '].join(", ") },');
  console.log(name + ': ' + width + 'x' + height + ' -> ' + widths.join(', '));
}
await writeFile(path.join(assets, 'responsive-images.ts'), '// Generated by npm run images:generate. Originals remain in src/assets.\n' + imports.join('\n') + '\n\nconst variants: Record<string, { width: number; height: number; srcSet: string }> = {\n' + records.join('\n') + '\n};\n\nexport function responsiveImage(src: string, sizes: string) {\n  return { ...variants[src], sizes };\n}\n');